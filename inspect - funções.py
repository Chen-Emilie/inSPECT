# Calcula a contagem total de pixels para cada frame de um arquivo dinâmico e armazena em uma lista de floats.
def contagem_dinamica(array):
  contagem_por_frame = []
  for frame in array:
    contagem_por_frame.append(float(np.sum(frame)))
  return contagem_por_frame

# Calcula a contagem total de pixels para o primeiro (e único) frame de um arquivo estático.
def contagem_estatica(array):
  if len(array) != 1:
    raise ValueError("A aquisição estática deve conter exatamente 1 frame.")
  return float(np.sum(array[0]))

# Calcula o valor do teste Qui-Quadrado para verificar a variância dos dados em relação à média.
def chi_quadrado(graus_liberdade, contagem):
  valores = np.asarray(contagem, dtype=float)

  if valores.size < 2:
    raise ValueError("A aquisição dinâmica precisa ter pelo menos dois frames.")
  if graus_liberdade <= 0:
    raise ValueError("Os graus de liberdade devem ser positivos.")

  media = float(np.mean(valores))
  if not np.isfinite(media) or media <= 0:
    raise ValueError("A contagem média dinâmica deve ser positiva.")

  desvio_padrao = float(np.std(valores, ddof=1))
  return (graus_liberdade * desvio_padrao**2) / media


# Calcula o valor P, que indica a probabilidade de a distribuição dos valores dos pixels ter ocorrido por acaso.
# Um valor P maior que 0.95 (ou 95%) é geralmente desejável, sugerindo que o processo é aleatório e estável.
def valor_p(chi_quadrado, graus_liberdade):
  valor_p = chi2.sf(chi_quadrado, graus_liberdade)
  return valor_p

# Extrai a duração total do exame em segundos a partir do metadado DICOM 'Effective Series Duration'.
def duracao_exame(arquivo, tag):
    if tag not in arquivo:
        raise ValueError(f"Metadado DICOM obrigatório ausente: {tag}.")

    valor = arquivo[tag].value
    if isinstance(valor, bytes):
        valor = valor.decode("ascii").strip("\x00 \t\r\n")

    if isinstance(valor, str) and "\\" in valor:
        itens = valor.split("\\")
    elif not isinstance(valor, (str, bytes)) and hasattr(valor, "__iter__"):
        itens = list(valor)
    else:
        itens = [valor]

    try:
        valores = [float(item) for item in itens]
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"Valor inválido para o metadado DICOM {tag}: {valor!r}."
        ) from exc

    if not valores or any(not math.isfinite(v) or v < 0 for v in valores):
        raise ValueError(f"Valor de duração inválido na tag {tag}: {valor!r}.")

    numero_frames = int(getattr(arquivo, "NumberOfFrames", 1))

    if tag == (0x0011, 0x100B):       # GE total duration, milliseconds
        duracao_s = sum(valores) / 1000.0
    elif tag == (0x0018, 0x1065):     # Frame Time Vector, milliseconds
        duracao_s = sum(valores) / 1000.0
    elif tag in ((0x0018, 0x1063), (0x0018, 0x1242)):
        # Frame Time / Actual Frame Duration, milliseconds per frame
        duracao_s = (
            sum(valores) if len(valores) > 1
            else valores[0] * numero_frames
        ) / 1000.0
    elif tag == (0x0018, 0x9073):     # Acquisition Duration, seconds total
        duracao_s = sum(valores)
    elif tag == (0x0018, 0x9220):     # Frame Acquisition Duration, seconds/frame
        duracao_s = (
            sum(valores) if len(valores) > 1
            else valores[0] * numero_frames
        )
    else:
        raise ValueError(f"Não há conversão de unidade definida para {tag}.")

    if not math.isfinite(duracao_s) or duracao_s <= 0:
        raise ValueError(
            f"A duração indicada pela tag {tag} deve ser positiva; "
            f"valor convertido: {duracao_s} s."
        )

    return duracao_s

# Calcula o 'tempo de frame aparente' com base nas contagens dinâmicas e estáticas, chi-quadrado e tempo de aquisição.
def tempo_frame_aparente(contagens_dinamicas, duracao_estatica_s, contagem_estatica):
  if not np.isfinite(duracao_estatica_s) or duracao_estatica_s <= 0:
    raise ValueError("A duração da aquisição estática deve ser positiva.")
  if not np.isfinite(contagem_estatica) or contagem_estatica <= 0:
    raise ValueError("A contagem estática deve ser positiva.")

  contagens = np.asarray(contagens_dinamicas, dtype=float).reshape(-1)
  if contagens.size == 0 or not np.all(np.isfinite(contagens)):
    raise ValueError("As contagens dinâmicas devem ser finitas e não vazias.")
  if np.any(contagens < 0):
    raise ValueError("As contagens dinâmicas não podem ser negativas.")

  # T_total_aparente = (sum(C_i) / C_s) * T_s
  return float(np.sum(contagens) * duracao_estatica_s / contagem_estatica)


def teste_temporizacao(tempo_total_aparente, duracao_dinamica_s):
  if not np.isfinite(tempo_total_aparente) or tempo_total_aparente < 0:
    raise ValueError("O tempo total aparente deve ser finito e não negativo.")
  if not np.isfinite(duracao_dinamica_s) or duracao_dinamica_s <= 0:
    raise ValueError("A duração dinâmica deve ser positiva.")

  limite_inferior = duracao_dinamica_s * 0.95
  limite_superior = duracao_dinamica_s * 1.05
  passou = limite_inferior <= tempo_total_aparente <= limite_superior
  status = "PASSOU" if passou else "FALHOU"

  mensagem = (
      f"Tempo total aparente: {tempo_total_aparente:.4f} s\n"
      f"Duração dinâmica nominal: {duracao_dinamica_s:.4f} s\n"
      f"Intervalo de tolerância (±5%): "
      f"{limite_inferior:.4f}–{limite_superior:.4f} s\n"
      f"Teste de temporização {status}."
  )
  return passou, mensagem

def pipeline_temporzacao(
    arquivo_dcm_estatico,
    arquivo_dcm_dinamico,
    save_report=True,
    output_dir=".",
    tag_duracao_estatica=(0x0018, 0x9073),
    tag_duracao_dinamica=(0x0018, 0x9073),
):
    dicom_estatico = ler_pydicom(arquivo_dcm_estatico)
    dicom_dinamico = ler_pydicom(arquivo_dcm_dinamico)

    frames_estaticos = arquivo_para_array(dicom_estatico)
    frames_dinamicos = arquivo_para_array(dicom_dinamico)

    if not frames_estaticos:
      raise ValueError("A aquisição estática não contém frames.")
    if len(frames_dinamicos) < 2:
      raise ValueError(
          "A aquisição dinâmica precisa conter pelo menos dois frames "
          "para o teste de temporização."
      )

    if len(frames_estaticos) != 1:
      raise ValueError(
          "A aquisição estática deve conter exatamente 1 frame "
          f"(foram encontrados {len(frames_estaticos)})."
      )

    contagem_estatica_valor = contagem_estatica(frames_estaticos)
    contagens_dinamicas = contagem_dinamica(frames_dinamicos)

    duracao_estatica = duracao_exame(
        dicom_estatico, tag_duracao_estatica
    )
    duracao_dinamica = duracao_exame(
        dicom_dinamico, tag_duracao_dinamica
    )

    graus_liberdade = len(contagens_dinamicas) - 1
    chi_valor = chi_quadrado(graus_liberdade, contagens_dinamicas)
    p_valor = valor_p(chi_valor, graus_liberdade)

    tempos_aparentes = tempo_frame_aparente(
        contagens_dinamicas,
        duracao_estatica,
        contagem_estatica_valor,
    )
    _, mensagem_temporizacao = teste_temporizacao(
        tempos_aparentes, duracao_dinamica
    )

    linhas = [
        f"Duração estática: {duracao_estatica:.4f} s",
        f"Duração dinâmica: {duracao_dinamica:.4f} s",
        (
            f"Contagem estática: {contagem_estatica_valor:.2f}; "
            f"contagem dinâmica total: {sum(contagens_dinamicas):.2f}"
        ),
        f"Valor do Qui-Quadrado: {chi_valor:.4f}",
        f"Valor P: {p_valor:.4f}",
    ]

    if p_valor > 0.05:
        linhas.append(
            "Resultado do Qui-Quadrado: PASSOU "
            "(p > 0,05; não se rejeita a hipótese de aleatoriedade)."
        )
    else:
        linhas.append(
            "Resultado do Qui-Quadrado: FALHOU "
            "(p <= 0,05; evidência de desvio da hipótese de aleatoriedade)."
        )

    linhas.append(mensagem_temporizacao)
    texto_resultado = "\n\n".join(linhas)

    if save_report:
        nome_base = os.path.splitext(
            os.path.basename(arquivo_dcm_dinamico)
        )[0]
        nome_saida = _nome_saida_com_timestamp(nome_base)
        pasta_relatorios = os.path.join(output_dir, "Relatórios")
        os.makedirs(pasta_relatorios, exist_ok=True)
        caminho_relatorio = os.path.join(
            pasta_relatorios,
            f"{nome_saida}_temporizacao_resultados.txt",
        )
        with open(caminho_relatorio, "w", encoding="utf-8") as arquivo:
            arquivo.write(texto_resultado)

    return texto_resultado

def _nome_saida_com_timestamp(nome_base):
  timestamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
  return f"{nome_base}_{timestamp}"