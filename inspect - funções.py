def ler_pydicom(arquivo_dcm):
  """
  Lê um arquivo DICOM (.dcm) e retorna o objeto DICOM lido.

  Args:
    arquivo_dcm (str): O caminho completo para o arquivo DICOM.

  Returns:
    pydicom.FileDataset: O objeto DICOM que contém os dados da imagem e metadados.
  """
  arquivo_lido = pydicom.dcmread(arquivo_dcm)
  return arquivo_lido

def arquivo_para_array(arquivo):
  """Retorna frames DICOM em escala de cinza como uma lista de arrays 2D."""
  pixels = np.asarray(arquivo.pixel_array)
  num_frames = int(getattr(arquivo, "NumberOfFrames", 1))
  samples_per_pixel = int(getattr(arquivo, "SamplesPerPixel", 1))

  if samples_per_pixel != 1:
    raise ValueError("A análise atual suporta apenas imagens DICOM em escala de cinza.")

  if num_frames == 1:
    if pixels.ndim != 2:
      raise ValueError(f"Formato inesperado para um frame: {pixels.shape}")
    return [pixels]

  if pixels.ndim != 3 or pixels.shape[0] != num_frames:
    raise ValueError(
        f"Esperados {num_frames} frames 2D, mas o formato encontrado foi {pixels.shape}."
    )

  return [pixels[i] for i in range(num_frames)]

