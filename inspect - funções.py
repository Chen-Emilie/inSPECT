def encontrar_phantom(frame):
  """
  Identifica e retorna o maior contorno (que representa o 'fantasma') e os pixels dentro dele
  em um determinado frame da imagem.

  Args:
    frame (numpy.ndarray): Um array NumPy representando um frame da imagem.

  Returns:
    tuple: Uma tupla contendo:
      - largest_contour (numpy.ndarray): O contorno do maior objeto encontrado.
      - combined_pixels (numpy.ndarray): Um array com os valores dos pixels dentro desse contorno.
  """
  frame = np.array(frame)
  # Normaliza o frame para 8 bits para processamento com OpenCV
  scaled_frame = cv2.normalize(frame, None, 0, 255, cv2.NORM_MINMAX, cv2.CV_8U)
  # Aplica limiarização para criar uma máscara binária
  _, binary_mask = cv2.threshold(scaled_frame, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)
  # Encontra os contornos na imagem binária
  contours, _ = cv2.findContours(
      binary_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
  )
  if not contours:
    return None, np.array([])

  largest_contour = max(contours, key=cv2.contourArea)

  # Cria uma máscara vazia e desenha o maior contorno nela
  mask = np.zeros_like(scaled_frame)
  cv2.drawContours(mask, [largest_contour], -1, 255, -1)

  # Extrai os pixels dentro do contorno
  pixels_inside_contour = frame[mask == 255]
  combined_pixels = pixels_inside_contour

  return (largest_contour, combined_pixels)

def display_phantom(frame_to_show, phantom_info, save_filename_base=None, output_dir="."):
  """
  Exibe o frame original e o frame com o contorno do 'fantasma' destacado em vermelho.
  Opcionalmente, salva a imagem resultante.

  Args:
    frame_to_show (numpy.ndarray): O frame da imagem a ser exibido.
    phantom_info (tuple): Uma tupla contendo (contorno_do_fantasma, pixels_do_fantasma).
    save_filename_base (str, optional): Nome base para salvar o arquivo de imagem. Se None, não salva.
  """
  largest_contour_from_func, pixels_inside_contour = phantom_info

  # Normaliza o frame para 8 bits para visualização com OpenCV
  # e converte para RGB para poder desenhar um contorno colorido
  frame_normalized_8bit = cv2.normalize(frame_to_show, None, 0, 255, cv2.NORM_MINMAX, cv2.CV_8U)
  frame_rgb = cv2.cvtColor(frame_normalized_8bit, cv2.COLOR_GRAY2RGB)

  # Cria uma cópia do frame normalizado para exibir o original
  original_frame_display = cv2.cvtColor(frame_normalized_8bit, cv2.COLOR_GRAY2RGB)

  # Desenha o maior contorno em vermelho na imagem RGB
  # Os argumentos são: imagem, contornos, índice do contorno (-1 para todos), cor, espessura
  cv2.drawContours(frame_rgb, [largest_contour_from_func], -1, (255, 0, 0), 2) # Contorno vermelho, espessura 2

  # Exibe ambas as imagens lado a lado
  fig, axes = plt.subplots(1, 2, figsize=(16, 8))

  axes[0].imshow(original_frame_display)
  axes[0].set_title('Frame Original')
  axes[0].axis('off')

  axes[1].imshow(frame_rgb)
  axes[1].set_title('Frame com Contorno do Fantasma')
  axes[1].axis('off')

  plt.tight_layout()
  if save_filename_base:
      pasta_imagens = os.path.join(output_dir, "Imagens")
      os.makedirs(pasta_imagens, exist_ok=True)
      save_path = os.path.join(
          pasta_imagens, f"{save_filename_base}_phantom_display.png"
      )
      fig.savefig(save_path)
  return fig

def analyze_and_visualize_phantom_data(
        all_phantom_pixels_data,
        first_frame_data,
        first_frame_phantom_info_data,
        current_lambda_poisson_from_mean,
        save_filename_base=None,
        output_dir="."):
  """
  Analisa os dados dos pixels do 'fantasma', plota um histograma com ajuste de Poisson,
  e exibe a máscara do 'fantasma' para o primeiro frame.

  Args:
    all_phantom_pixels_data (list or array): Conjunto de todos os valores de pixels do 'fantasma' coletados.
    first_frame_data (numpy.ndarray): O primeiro frame dos dados da imagem.
    first_frame_phantom_info_data (tuple): Uma tupla contendo (maior_contorno, pixels_dentro_do_contorno)
                                            para o primeiro frame, conforme retornado por `encontrar_phantom`.
                                            Pode ser None para análise do frame completo.
    current_lambda_poisson_from_mean (float): O parâmetro lambda (média) da
                                      distribuição de Poisson esperada, previamente calculado.
    save_filename_base (str, optional): Nome base para salvar os gráficos. Padrão é None.
  """
  # 1. Plota o histograma da frequência de todos os valores de pixel e a distribuição de Poisson

  # Determina lambda para o ajuste de Poisson com base nas condições
  if len(all_phantom_pixels_data) == 0:
    lambda_poisson = current_lambda_poisson_from_mean # Usa a média como alternativa se não houver dados
    max_pixel_value = 0 # Sem pixels, então o máximo é 0
    min_pixel_value = 0
  else:
    max_pixel_value = np.max(all_phantom_pixels_data)
    min_pixel_value = np.min(all_phantom_pixels_data) # Também obtém o mínimo para o intervalo do gráfico
    if max_pixel_value > 100 and np.mean(all_phantom_pixels_data) > 100: # Heurística para valores de pixel altos
      # Aplica lógica de busca de pico se o valor máximo do pixel e a média forem altos
      # Cria bins mais granulares para o histograma para encontrar um pico melhor
      hist_bins = np.arange(min_pixel_value, max_pixel_value + 2) - 0.5
      hist, bin_edges = np.histogram(all_phantom_pixels_data, bins=hist_bins)
      peak_index = np.argmax(hist)
      lambda_poisson = int(bin_edges[peak_index] + 0.5)
    else:
      # Caso contrário, usa a média como antes
      lambda_poisson = current_lambda_poisson_from_mean

  # Garante que os valores dos pixels são inteiros para os bins do histograma e arange
  max_pixel_value = int(max_pixel_value)
  min_pixel_value = int(min_pixel_value)

  # Calcula x para a PMF de Poisson, focando em torno de lambda_poisson
  if lambda_poisson > 0 and len(all_phantom_pixels_data) > 0:
      std_dev_poisson = np.sqrt(lambda_poisson)
      # Estende 5 desvios padrão em torno da média, mas também cobre os valores mínimos/máximos observados
      x_start_poisson = max(0, int(lambda_poisson - 5 * std_dev_poisson))
      x_end_poisson = int(lambda_poisson + 5 * std_dev_poisson + 1)

      # Garante que o intervalo do gráfico inclui os valores mínimos e máximos de pixel observados
      x_min_plot = min(x_start_poisson, min_pixel_value)
      x_max_plot = max(x_end_poisson, max_pixel_value + 1)

      x = np.arange(x_min_plot, x_max_plot + 1)

  else: # Lida com casos onde lambda é 0 ou não há dados, ou valores pequenos
      x = np.arange(min_pixel_value, max_pixel_value + 2) # Cobre o intervalo observado
      if len(all_phantom_pixels_data) == 0:
          x = np.arange(0, 10) # Padrão para dados vazios

  poisson_pmf = poisson.pmf(x, lambda_poisson) * len(all_phantom_pixels_data)

  fig_hist = plt.figure(figsize=(10, 6))
  plt.hist(all_phantom_pixels_data, bins=np.arange(min_pixel_value, max_pixel_value + 2) - 0.5, density=False, alpha=0.7, label='Dados Observados')
  plt.plot(x, poisson_pmf, 'ro-', label=f'Ajuste de Poisson (λ={lambda_poisson:.2f})')
  plt.title("Histograma dos Valores de Pixel e Distribuição de Poisson Ajustada")
  plt.xlabel("Valor do Pixel")
  plt.ylabel("Frequência")
  plt.legend()

  # Define os limites do eixo x para focar no intervalo relevante, garantindo que cubra todos os pontos plotados
  if len(x) > 1: # Garante que x tem pontos suficientes para limites significativos
    plt.xlim(x.min() - 0.5, x.max() + 0.5)
  elif len(all_phantom_pixels_data) > 0: # Se x é muito pequeno mas existem dados
    plt.xlim(min_pixel_value - 1, max_pixel_value + 1)
  else: # Alternativa para quando não há dados
    plt.xlim(-1, 10) # Um pequeno intervalo padrão
  

  if save_filename_base:
      pasta_imagens = os.path.join(output_dir, "Imagens")
      os.makedirs(pasta_imagens, exist_ok=True)
      save_path = os.path.join(
          pasta_imagens, f"{save_filename_base}_histogram.png"
      )
      fig_hist.savefig(save_path)

  phantom_fig = None
  if first_frame_phantom_info_data is not None:
      phantom_fig = display_phantom(
          first_frame_data,
          first_frame_phantom_info_data,
          save_filename_base,
          output_dir,
      )

  return fig_hist, phantom_fig

def run_analysis_pipeline_extrinsico(
    dcm_filepath, save_images=True, save_report=True, output_dir="."
):
  """
  Executa um pipeline de análise completo para um dado arquivo DICOM extrínseco:
  1. Lê o arquivo DICOM.
  2. Converte-o em um array de frames.
  3. Encontra os pixels do 'fantasma' para cada frame.
  4. Exibe a máscara do 'fantasma' para o primeiro frame.
  5. Plota um histograma de todos os pixels do 'fantasma' com um ajuste de Poisson.

  Args:
    dcm_filepath (str): O caminho para o arquivo DICOM.

  Returns:
    tuple: (lambda_poisson, first_frame, first_frame_phantom_info) ou (None, None, None)
           se nenhum frame ou informação do 'fantasma' for encontrado.
  """

  # Extrai o nome base do arquivo DICOM para salvar os gráficos
  dcm_filename_base = os.path.splitext(os.path.basename(dcm_filepath))[0]
  nome_saida = _nome_saida_com_timestamp(dcm_filename_base)

  dcm_data = ler_pydicom(dcm_filepath)
  frames = arquivo_para_array(dcm_data)

  all_phantom_pixels = []
  first_frame = None
  first_frame_phantom_info = None

  # 3. Processa cada frame para encontrar os pixels do 'fantasma'
  for frame in frames:
    contour, pixels = encontrar_phantom(frame)
    if contour is None or pixels.size == 0:
      continue

    if first_frame is None:
      first_frame = frame
      first_frame_phantom_info = (contour, pixels)

    all_phantom_pixels.extend(pixels)

  if first_frame is None or not all_phantom_pixels:
    return None, None, None, (None, None)

  lambda_poisson = float(np.mean(all_phantom_pixels))
  figures = analyze_and_visualize_phantom_data(
      all_phantom_pixels,
      first_frame,
      first_frame_phantom_info,
      lambda_poisson,
      nome_saida if save_images else None,
      output_dir=output_dir,
  )

  if save_report:
    pasta_relatorios = os.path.join(output_dir, "Relatórios")
    os.makedirs(pasta_relatorios, exist_ok=True)
    caminho_relatorio = os.path.join(
        pasta_relatorios, f"{nome_saida}_resultados.txt"
    )
    with open(caminho_relatorio, "w", encoding="utf-8") as arquivo:
      arquivo.write("Aquisição extrínseca: análise concluída.\n")

  return lambda_poisson, first_frame, first_frame_phantom_info, figures


def run_analysis_pipeline_intrinsico(
    dcm_filepath, save_images=True, save_report=True, output_dir="."
):
  """Analisa a ROI retangular dos pixels não zero de uma aquisição intrínseca."""
  dcm_filename_base = os.path.splitext(os.path.basename(dcm_filepath))[0]
  nome_saida = _nome_saida_com_timestamp(dcm_filename_base)
  dcm_data = ler_pydicom(dcm_filepath)
  frames = arquivo_para_array(dcm_data)

  all_intrinsic_pixels = []
  first_frame_for_display = None
  first_frame_phantom_info = None

  for frame in frames:
    non_zero_coords = np.argwhere(frame > 0)
    if non_zero_coords.size == 0:
      continue

    y_min, x_min = non_zero_coords.min(axis=0)
    y_max, x_max = non_zero_coords.max(axis=0)
    roi_pixels = frame[y_min:y_max + 1, x_min:x_max + 1].flatten()
    all_intrinsic_pixels.extend(roi_pixels)

    # Use the first frame that actually contains a valid ROI.
    if first_frame_for_display is None:
      contour = np.array(
          [
              [[x_min, y_min]],
              [[x_max, y_min]],
              [[x_max, y_max]],
              [[x_min, y_max]],
          ],
          dtype=np.int32,
      )
      first_frame_for_display = frame
      first_frame_phantom_info = (contour, roi_pixels)

  if not all_intrinsic_pixels:
    return None, None, (None, None)

  all_intrinsic_pixels = np.asarray(all_intrinsic_pixels)
  lambda_poisson = float(np.mean(all_intrinsic_pixels))

  figures = analyze_and_visualize_phantom_data(
      all_intrinsic_pixels,
      first_frame_for_display,
      first_frame_phantom_info,
      lambda_poisson,
      nome_saida if save_images else None,
      output_dir=output_dir,
  )

  if save_report:
    pasta_relatorios = os.path.join(output_dir, "Relatórios")
    os.makedirs(pasta_relatorios, exist_ok=True)
    caminho_relatorio = os.path.join(
        pasta_relatorios, f"{nome_saida}_resultados.txt"
    )
    with open(caminho_relatorio, "w", encoding="utf-8") as arquivo:
      arquivo.write("Aquisição intrínseca: análise concluída.\n")

  return lambda_poisson, first_frame_for_display, figures

